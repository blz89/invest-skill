# DeepSeek 计费时段：工作日 09:00-12:00 / 14:00-18:00 为标准价，其余半价
OFFPEAK = {
    "enabled": True,
    "tz": "Asia/Shanghai",
    "peak_windows": [("09:00", "12:00"), ("14:00", "18:00")],
    "holidays": [],          # 法定节假日（YYYY-MM-DD），可被 CACHE_DIR/offpeak_holidays.json 覆盖
}


def is_offpeak(when=None) -> bool:
    """现在是否 DeepSeek 空闲时段（半价）。

    规则（2026-10 官方价目页）：工作日 09:00-12:00、14:00-18:00 为标准价；
    其余时间、周末、法定节假日全天为半价。
    法定节假日取 `OFFPEAK["holidays"]` 或 `CACHE_DIR/offpeak_holidays.json`。
    """
    if not OFFPEAK.get("enabled", True):
        return False
    t = when or __import__("datetime").datetime.now()
    days = OFFPEAK.get("holidays") or []
    if not days:
        try:
            path = os.path.join(CACHE_DIR, "offpeak_holidays.json")
            if os.path.exists(path):
                import json as _json
                with open(path, encoding="utf-8") as f:
                    days = _json.load(f)
        except Exception:       # noqa: BLE001
            days = []
    if t.strftime("%Y-%m-%d") in set(days or []):
        return True
    if t.weekday() >= 5:        # 周六日
        return True
    hm = t.strftime("%H:%M")
    for a, b in OFFPEAK.get("peak_windows") or []:
        if a <= hm < b:
            return False
    return True


