def _industry_hook(df):
    """把百度行业口径（如「服装鞋类」）映射到同花顺一级行业（如「交通运输」）。

    stock 的数据层只负责取原始字段；行业修正表是 invest 自己的策略口径，
    所以通过钩子留在技能侧（见 industry.normalize）。
    """
    import industry as _industry  # 延迟导入：industry.py 顶部 import config，避免循环
    df = df.copy()
    df["industry"] = [_industry.normalize(v, c)
                      for v, c in zip(df["industry"], df["code"])]
    return df


_DATASOURCE.set_market_hook(_industry_hook)
